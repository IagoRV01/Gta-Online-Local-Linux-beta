# Regenerates src/engine/natives.h with every N_<NAME> used under src/.
# Native database: alloc8or/gta5-nativedb-data natives.json (git-ignored; see candidates below).
# Fails loudly on unknown names, so a typo in a native name is a build error, not a crash in game.
import glob
import json
import os
import re
import sys

root = os.path.normpath(os.path.join(os.path.dirname(__file__), '..'))
# tools/natives.json (git-ignored download) first, then the copy shared with the sibling gta-mods projects.
candidates = [os.path.join(root, 'tools', 'natives.json'),
              os.path.join(root, '..', '..', 'gori-online', 'natives.json'),
              os.path.join(root, '..', '..', '..', 'gta-mods', 'GoriOnlineNative', 'natives.json')]
db_path = next((p for p in candidates if os.path.exists(p)), None)
if not db_path:
    if os.path.exists(os.path.join(root, 'src', 'engine', 'natives.h')):   # the committed header is enough to build
        print('natives.json not found: keeping src/engine/natives.h')
        sys.exit(0)
    sys.exit('natives.json not found (looked in: %s)' % ', '.join(candidates))

db = json.load(open(db_path, encoding='utf-8'))
index = {}
for ns, funcs in db.items():
    for h, f in funcs.items():
        index[f['name']] = (h, f)

out_path = os.path.join(root, 'src', 'engine', 'natives.h')
used = set()
for p in glob.glob(os.path.join(root, 'src', '**', '*.*'), recursive=True):
    if os.path.normpath(p) == os.path.normpath(out_path) or not p.endswith(('.cpp', '.h')):
        continue
    used |= set(re.findall(r'\bN_([A-Z0-9_]+)\b', open(p, encoding='utf-8').read()))

missing = sorted(u for u in used if u not in index)
if missing:
    sys.exit('unknown natives: ' + ', '.join(missing))

lines = ['// Generated by tools/gen_natives.py from alloc8or/gta5-nativedb-data. Do not edit.',
         '#pragma once', '#include <cstdint>']
for u in sorted(used):
    h, f = index[u]
    params = ', '.join(p['type'] + ' ' + p['name'] for p in f.get('params', []))
    lines.append('constexpr uint64_t N_%s = %s;  // %s %s(%s)' % (u, h, f.get('return_type', 'void'), u, params))
new = '\n'.join(lines) + '\n'
old = open(out_path, encoding='utf-8').read() if os.path.exists(out_path) else ''
if new != old:
    open(out_path, 'w', encoding='utf-8', newline='\n').write(new)
print('%d natives -> %s' % (len(used), os.path.relpath(out_path, root)))
