# Embeds a .sql file as a C++ raw string constant (kSchemaSql). Used by build.sh.
import sys
sql = open(sys.argv[1], encoding='utf-8').read()
out = ('// Generated by tools/embed_sql.py from %s. Do not edit.\n#pragma once\n'
       'static const char *kSchemaSql = R"SQL(%s)SQL";\n') % (sys.argv[1], sql)
old = open(sys.argv[2], encoding='utf-8').read() if __import__('os').path.exists(sys.argv[2]) else ''
if out != old:
    open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write(out)
