# Regenerates arena_outfits.h: Arena War's own outfits (the mpchristmas2018 shop metas' pedOutfits with the lock
# CU_ARENA_CLOTHES), male and female, for the Arena career's rewards (ArenaWar.inc).
# Usage: python tools/gen_arena_outfits.py <shop_m.meta> <shop_f.meta>
#   (extract: IslandBuilder.dll "<GTA dir>" extract update/update.rpf
#    "mpchristmas2018\common\data\mp_m_freemode_01_mpchristmas2018_shop.meta" <out>, and the same with mp_f)
import os, sys, xml.etree.ElementTree as ET
here = os.path.join(os.path.dirname(__file__), '..')
COMP = {'PV_COMP_HEAD': 0, 'PV_COMP_BERD': 1, 'PV_COMP_HAIR': 2, 'PV_COMP_UPPR': 3, 'PV_COMP_LOWR': 4, 'PV_COMP_HAND': 5,
        'PV_COMP_FEET': 6, 'PV_COMP_TEEF': 7, 'PV_COMP_ACCS': 8, 'PV_COMP_TASK': 9, 'PV_COMP_DECL': 10, 'PV_COMP_JBIB': 11}
ANCHOR = {'ANCHOR_HEAD': 0, 'ANCHOR_EYES': 1, 'ANCHOR_EARS': 2, 'ANCHOR_MOUTH': 3, 'ANCHOR_LEFT_HAND': 4,
          'ANCHOR_RIGHT_HAND': 5, 'ANCHOR_LEFT_WRIST': 6, 'ANCHOR_RIGHT_WRIST': 7, 'ANCHOR_HIP': 8}

def outfits(path):
    root = ET.parse(path).getroot()
    res = []
    for it in root.find('pedOutfits').findall('Item'):
        if it.findtext('lockHash') != 'CU_ARENA_CLOTHES': continue
        name, label = it.findtext('uniqueNameHash'), it.findtext('textLabel')
        parts = []   # (kind 0 component / 1 prop, slot, name or '', enum)
        for c in it.find('includedPedComponents').findall('Item'):
            parts.append((0, COMP[c.findtext('eCompType')], c.findtext('nameHash'), int(c.find('enumValue').get('value'))))
        props = it.find('includedPedProps')
        for p in (props.findall('Item') if props is not None else []):
            parts.append((1, ANCHOR[p.findtext('eAnchorPoint')], p.findtext('nameHash'), int(p.find('enumValue').get('value'))))
        res.append((name, label, parts))
    return res

def family(name):   # DLC_MP_ARENA_M_OUTFIT_SPACE_A_3 -> SPACE_A
    return name.split('_OUTFIT_', 1)[1].rsplit('_', 1)[0]

out = ['// Generated by tools/gen_arena_outfits.py from the mpchristmas2018 shop metas: Arena War\'s own outfits.',
       '// A part: {kind (0 a component, 1 a prop), slot, the item\'s name (nullptr: the plain drawable "value"), value}.',
       '#pragma once', 'struct AwOutfitPart { int kind, slot; const char *name; int value; };',
       'struct AwOutfitDef { const char *name, *label, *family; int nParts; AwOutfitPart parts[8]; };']
for g, path in (('M', sys.argv[1]), ('F', sys.argv[2])):
    lst = outfits(path)
    out.append('static const AwOutfitDef AW_OUTFITS_%s[] = {' % g)
    for name, label, parts in lst:
        assert len(parts) <= 8, name
        ps = ', '.join('{%d, %d, %s, %d}' % (k, s, ('"%s"' % n) if n and n != '0' else 'nullptr', v) for k, s, n, v in parts)
        out.append('    {"%s", "%s", "%s", %d, {%s}},' % (name, label, family(name), len(parts), ps))
    out.append('};')
    print(g, len(lst), 'outfits')
open(os.path.join(here, 'arena_outfits.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
