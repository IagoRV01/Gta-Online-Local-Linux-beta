# Generates ammunation.h: GTA Online's Ammu-Nation catalogue (weapon, price, rounds given with it, shop
# category) as gunclub_shop.ysc prices them in multiplayer (func_219's NETWORK_IS_GAME_IN_PROGRESS branch),
# tunables at their defaults (tuneables_processing.ysc). Both scripts decompiled, next to each other.
#
#   python tools/gen_ammunation.py <gunclub_shop.c> <tuneables_processing.c> [ammunation.h]
import re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(sys.argv[1], encoding='utf-8', errors='replace').read().split('\n')
tp = open(sys.argv[2], encoding='utf-8', errors='replace').read()
out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(here, '..', 'ammunation.h')

tun = {}
for m in re.finditer(r'Global_262145\.f_(\d+) = NETWORK::_NETWORK_GET_TUNABLES_REGISTRATION_(?:INT|FLOAT)\([^,]+,\s*(-?[\d.]+)f?\)', tp):
    tun[int(m.group(1))] = float(m.group(2))

start = next(i for i, l in enumerate(src) if l.startswith('BOOL func_219('))
end = next(i for i in range(start, len(src)) if src[i] == '}')
body = src[start:end]
mp = next(i for i, l in enumerate(body) if l == '\telse')
rows, cur, pend = [], [], {}
for l in body[mp:]:
    m = re.match(r'^\t+case joaat\("(\w+)"\):$', l)
    if m: cur.append(m.group(1)); continue
    if re.match(r'^\t+break;$', l):
        for w in cur: rows.append((w, dict(pend)))
        cur, pend = [], {}; continue
    if not cur: continue
    m = re.match(r'^\t+\*uParam([12]) = (-?\d+);$', l)
    if m: pend.setdefault('d' + m.group(1), int(m.group(2))); continue
    m = re.match(r'^\t+\*uParam([12]) = \*?Global_262145\.f_(\d+);$', l)
    if m: pend.setdefault('t' + m.group(1), int(m.group(2))); continue
    m = re.match(r'^\t+num2 = (\d+);$', l)
    if m: pend['cat'] = int(m.group(1))
    m = re.match(r'^\t+\*uParam([12]) = \*Global_262145\.f_(\d+);?.*$', l)
    if m: pend.setdefault('t' + m.group(1), int(m.group(2)))

def val(r, k):
    # "if (tunable == -1) default else tunable": the tunable's own default wins when it is registered
    t = r.get('t' + k)
    if t is not None and t in tun and tun[t] >= 0: return int(tun[t])
    return r.get('d' + k)

L = ['// Generated by tools/gen_ammunation.py from GTA Online\'s gunclub_shop.ysc (func_219, multiplayer prices)',
     '// and tuneables_processing.ysc (tunable defaults). Do not edit.',
     '// cat: 1 SMG, 2 shotgun, 3 rifle, 4 sniper, 5 MG, 6 heavy, 7 melee, 8 pistol, 9 thrown, 10 jerry can',
     'struct AmmuWeapon { const char *weapon; int price, rounds, cat; };',
     'static const AmmuWeapon AMMU_WEAPONS[] = {']
seen = set()
for w, r in rows:
    if w in seen or 'cat' not in r or r['cat'] > 10: continue
    p = val(r, '1')
    if p is None or p <= 0: continue
    seen.add(w)
    L.append('    {"%s", %d, %d, %d},' % (w, p, val(r, '2') or 0, r['cat']))
L += ['};', 'static const int NAMMU_WEAPONS = (int)(sizeof AMMU_WEAPONS / sizeof *AMMU_WEAPONS);', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))
print(len(seen), 'weapons ->', out)
