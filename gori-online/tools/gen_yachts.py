# Generates yachts.h: GTA Online's 36 Super Yacht moorings (12 places x 3) and its yacht flags.
# The moorings are the apa_yacht_grpNN_M ymaps (the hull, its interior apa_mpapa_yacht) from
# DurtyFree/gta-v-data-dumps (ipls.json: the ymap's centre; mloInteriors.json: the interior's origin);
# the flags are freemode's func_1815.
#
#   python tools/gen_yachts.py <ipls.json> <mloInteriors.json> <freemode.c> [yachts.h]
import json, re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
ipls = json.load(open(sys.argv[1], encoding='utf-8'))
mlo = json.load(open(sys.argv[2], encoding='utf-8'))
fm = open(sys.argv[3], encoding='utf-8', errors='replace').read()
out = sys.argv[4] if len(sys.argv) > 4 else os.path.join(here, '..', 'yachts.h')

ext = {x['Name']: x['Position'] for x in ipls if re.fullmatch(r'apa_yacht_grp\d\d_\d', x['Name'])}
ints = {}
for m in mlo:
    if m['Name'] != 'apa_mpapa_yacht': continue
    for loc in m['Locations']:
        n = re.search(r'(apa_yacht_grp\d\d_\d)_int\.ymap', loc['FilePath'])
        if n: ints[n.group(1)] = loc['Position']
rows = []
for name in sorted(ext):
    g, k = int(name[13:15]), int(name[16])
    e, i = ext[name], ints.get(name)
    if not i: continue
    rows.append((g, k, name, e, i))

m = re.search(r'Hash func_1815\(int iParam0, BOOL bParam1\).*?\n}\n', fm, re.S)
flags = re.findall(r'case (\d+):\s*return joaat\("(apa_prop_flag_\w+)"\);', m.group(0))

L = ['// Generated by tools/gen_yachts.py (DurtyFree gta-v-data-dumps ipls.json / mloInteriors.json, freemode.ysc). Do not edit.',
     '// GTA Online Super Yacht moorings: group (place), slot, ymap, ymap centre (the hull), interior origin.',
     '#pragma once',
     'struct YachtSpot { int group, slot; const char *ipl; float x, y, z, ix, iy, iz; };',
     'static const YachtSpot YACHT_SPOTS[] = {']
for g, k, name, e, i in rows:
    L.append('    {%d, %d, "%s", %.3ff, %.3ff, %.3ff, %.3ff, %.3ff, %.3ff},' % (g, k, name, e['X'], e['Y'], e['Z'], i['X'], i['Y'], i['Z']))
L += ['};', 'static const int NYACHT_SPOTS = (int)(sizeof YACHT_SPOTS / sizeof *YACHT_SPOTS);',
      '// freemode func_1815: the flag (Docktease "personalise") -> its model', 'static const char *YACHT_FLAGS[] = {']
for idx, f in sorted(flags, key=lambda t: int(t[0])): L.append('    "%s",   // %s' % (f, idx))
L += ['};', 'static const int NYACHT_FLAGS = (int)(sizeof YACHT_FLAGS / sizeof *YACHT_FLAGS);', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))
print(len(rows), 'moorings,', len(flags), 'flags ->', out)
