# Generates warstock_specials.h: the data GTA Online's appinternet sends to Warstock's configurators
# (MOC "TRUCK", Avenger "CHOPPER", Terrorbyte "HACKER", Kosatka "SUB") when you own none of them:
# func_8830 (slots 10-14), func_8824 (15-17), func_8819 (18-24), func_8812 (25-...), run in ysc_eval with
# the tunables' default prices. The first row of each feed is the owned configuration: Gori Online
# rewrites it at run time.
#
#   python tools/gen_warstock_specials.py <appinternet.c> [warstock_specials.h]   (tuneables_processing.c next to it)
import re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from ysc_eval import Ysc, Recorder, joaat

src_path = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', 'warstock_specials.h')
folder = os.path.dirname(os.path.abspath(src_path))
tp = open(os.path.join(folder, 'tuneables_processing.c'), encoding='utf-8', errors='replace').read()
R = r'Global_262145\.(f_\d+(?:\[\d+\])?) = NETWORK::_NETWORK_GET_TUNABLES_REGISTRATION_%s\((?:joaat\("[^"]+"\)[^,]*|-?\d+), (%s)\);'
tun = {k: int(v) for k, v in re.findall(R % ('INT', r'-?\d+'), tp)}
tun.update({k: (1 if v == 'true' else 0) for k, v in re.findall(R % ('BOOL', 'true|false'), tp)})
tun.update({k: float(v.rstrip('f')) for k, v in re.findall(R % ('FLOAT', r'-?[\d.]+f?'), tp)})

# vehicle prices come from Rockstar's catalogue server in GTA Online; the GTA wiki's
TERRORBYTE = 1375000
CABS = {joaat('phantom3'): 1225000, joaat('hauler2'): 1400000}
over = {
    'func_8684': lambda h=0, *a: CABS.get(h, 0),            # a cab's price
    'func_8836': lambda *a: min(CABS.values()),              # "buy from": the cheapest cab
    'func_8832': lambda *a: min(CABS.values()),
    'func_8823': lambda *a: TERRORBYTE, 'func_8821': lambda *a: TERRORBYTE,   # the Terrorbyte's own price
    'func_8822': lambda *a: TERRORBYTE, 'func_8820': lambda *a: TERRORBYTE,   # "buy from"
}
tun['f_9329'] = 0   # no sales: every *_sale_cost stays -1 ("no sale" to the site)
ev = Ysc(open(src_path, encoding='utf-8', errors='replace').read(), tun, overrides=over)

# Docktease's yacht (func_8838, dataProviderUI[18] of that site): first purchase and upgrade prices
FEEDS = [('truck', 'func_8830', [0, 0]), ('chopper', 'func_8824', [0, 0]), ('hacker', 'func_8819', [0, 0]), ('sub', 'func_8812', [0, 0]),
         ('yacht', 'func_8838', [0, 18, 0, 0, 0, 'UPDATE']), ('yacht_owned', 'func_8838', [0, 18, 1, 0, 0, 'UPDATE'])]
rows = []
for name, fn, args in FEEDS:
    rec = Recorder(); ev.rec = rec
    ev.call(fn, args)
    for m, ps in rec.calls:
        if m not in ('SET_DATA_SLOT', 'APPEND_YACHT_DATA_SLOT'): continue
        vals = []
        for kind, v in ps:
            if isinstance(v, tuple): v = v[0]
            if kind == 'LABEL': vals.append(('s', str(v)))
            elif kind == 'PLAYER_NAME_STRING': vals.append(('n', str(v) if isinstance(v, str) else ''))
            elif kind == 'FLOAT': vals.append(('f', float(v)))
            elif kind == 'BOOL': vals.append(('b', 1 if v else 0))
            else: vals.append(('i', int(v) if not isinstance(v, str) else 0))
        rows.append((name, m, vals))

L = ['// Generated by tools/gen_warstock_specials.py from GTA Online\'s appinternet.ysc (decompiled). Do not edit.',
     '// Warstock configurator data (SET_DATA_SLOT slot, values...) for MOC / Avenger / Terrorbyte / Kosatka,',
     '// nothing owned, default tunable prices. kind: i int, f float, b bool, s label, n player-name string.',
     '#pragma once',
     'struct WsVal { char kind; int i; float f; const char *s; };',
     'struct WsRow { const char *feed, *method; int nvals; const WsVal *vals; };']
for k, (name, m, vals) in enumerate(rows):
    items = ', '.join('{\'%s\', %d, %.2ff, %s}' % (t, v if t in 'ib' else 0, v if t == 'f' else 0.0, ('"%s"' % v) if t in 'sn' else 'nullptr') for t, v in vals)
    L.append('static const WsVal WS_V%d[] = {%s};' % (k, items))
L.append('static const WsRow WS_ROWS[] = {')
for k, (name, m, vals) in enumerate(rows):
    L.append('    {"%s", "%s", %d, WS_V%d},' % (name, m, len(vals), k))
L += ['};', 'static const int NWS_ROWS = (int)(sizeof WS_ROWS / sizeof *WS_ROWS);', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))
for name, m, vals in rows:
    print('%-11s %-22s slot %-3s %s' % (name, m, vals[0][1] if vals else '?', [v for t, v in vals[1:]]))
