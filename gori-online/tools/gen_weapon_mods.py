# Generates weapon_mods.h: GTA Online's weapon attachments for the base-game weapons, as gunclub_shop.ysc
# prices them in multiplayer (func_166's NETWORK_IS_GAME_IN_PROGRESS branch, tunable multipliers at their
# default 1.0) with their names (func_168). DLC weapons (Mk II included) are read in game from
# GET_DLC_WEAPON_COMPONENT_DATA instead, like the shop does.
#
#   python tools/gen_weapon_mods.py <gunclub_shop.c> [weapon_mods.h]
import re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from ysc_eval import Ysc, joaat

src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', 'weapon_mods.h')
L = src.split('\n')
start = next(i for i, l in enumerate(L) if re.match(r'^int func_166\(', l))
end = next(i for i in range(start, len(L)) if L[i] == '}')
# the multiplayer branch: after the "else" of if (!NETWORK_IS_GAME_IN_PROGRESS())
mp = next(i for i in range(start, end) if L[i] == '\telse' and L[i + 2].strip() == 'num = 2.5f;')
rows, weapon, comp = [], None, None
for l in L[mp:end]:
    m = re.match(r'^\t\t\tcase joaat\("(WEAPON_\w+)"\):$', l)
    if m: weapon = m.group(1); continue
    if re.match(r'^\t\t\tdefault:', l): weapon = None; continue
    m = re.match(r'^\t\t\t\t\tcase joaat\("(COMPONENT_\w+)"\):$', l)
    if m and weapon: comp = m.group(1); continue
    m = re.match(r'^\t\t\t\t\t\tprice = (-?\d+);$', l)
    if m and weapon and comp:
        rows.append([weapon, comp, int(m.group(1))]); comp = None
ev = Ysc(src, {})
for r in rows:
    lab = ev.call('func_168', [joaat(r[1]), joaat(r[0])])
    r.append(lab if isinstance(lab, str) else '')
lines = ['// Generated by tools/gen_weapon_mods.py from GTA Online\'s gunclub_shop.ysc (decompiled). Do not edit.',
         '// Base-game weapon attachments: weapon, component, GTA Online price (-1: not sold), name label.',
         '#pragma once',
         'struct WeaponModRow { const char *weapon, *component; int price; const char *label; };',
         'static const WeaponModRow WEAPON_MODS[] = {']
for w, c, p, lab in rows: lines.append('    {"%s", "%s", %d, "%s"},' % (w, c, p, lab))
lines += ['};', 'static const int NWEAPON_MODS = (int)(sizeof WEAPON_MODS / sizeof *WEAPON_MODS);', '']
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print(len(rows), 'attachments for', len({r[0] for r in rows}), 'weapons;', sum(1 for r in rows if not r[3]), 'without a label ->', out)
for r in rows[:6]: print(' ', r)
